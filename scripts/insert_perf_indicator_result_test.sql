-- 业绩看板-指标结果测试数据
-- 使用方式：
-- 1. 先执行 insert_org_unit.sql
-- 2. 先执行 insert_perf_indicator_seed.sql
-- 3. 再执行本脚本，生成 perf_indicator_result 测试数据
-- 说明：
-- - 数据日期使用当前日期及前 29 天，共 30 天
-- - 指标仅使用 seed 文件里已经存在的叶子指标 ID
-- - 机构仅使用 insert_org_unit.sql 里已经存在的一部分机构编码
-- - 440 类指标同时生成 metric_value(日均) 和 metric_value_2(时点)
-- - 380 / 480 类指标仅生成 metric_value_2，便于测试“无日均值返回空列表”

INSERT IGNORE INTO `perf_indicator_result`
(`data_dt`, `indicator_id`, `org_id`, `metric_value`, `metric_value_2`, `calc_status`)
SELECT
    dt.data_dt,
    ind.indicator_id,
    org.org_id,
    CASE
        WHEN ind.has_metric_value = 1 THEN ROUND((10000 + ind.indicator_id * 97 + org.org_idx * 13 + dt.day_offset * 11) / 100, 2)
        ELSE NULL
    END AS metric_value,
    ROUND((20000 + ind.indicator_id * 131 + org.org_idx * 17 + dt.day_offset * 19) / 100, 2) AS metric_value_2,
    '01' AS calc_status
FROM (
    SELECT 0 AS day_offset, DATE_SUB(CURDATE(), INTERVAL 0 DAY) AS data_dt
    UNION ALL SELECT 1, DATE_SUB(CURDATE(), INTERVAL 1 DAY)
    UNION ALL SELECT 2, DATE_SUB(CURDATE(), INTERVAL 2 DAY)
    UNION ALL SELECT 3, DATE_SUB(CURDATE(), INTERVAL 3 DAY)
    UNION ALL SELECT 4, DATE_SUB(CURDATE(), INTERVAL 4 DAY)
    UNION ALL SELECT 5, DATE_SUB(CURDATE(), INTERVAL 5 DAY)
    UNION ALL SELECT 6, DATE_SUB(CURDATE(), INTERVAL 6 DAY)
    UNION ALL SELECT 7, DATE_SUB(CURDATE(), INTERVAL 7 DAY)
    UNION ALL SELECT 8, DATE_SUB(CURDATE(), INTERVAL 8 DAY)
    UNION ALL SELECT 9, DATE_SUB(CURDATE(), INTERVAL 9 DAY)
    UNION ALL SELECT 10, DATE_SUB(CURDATE(), INTERVAL 10 DAY)
    UNION ALL SELECT 11, DATE_SUB(CURDATE(), INTERVAL 11 DAY)
    UNION ALL SELECT 12, DATE_SUB(CURDATE(), INTERVAL 12 DAY)
    UNION ALL SELECT 13, DATE_SUB(CURDATE(), INTERVAL 13 DAY)
    UNION ALL SELECT 14, DATE_SUB(CURDATE(), INTERVAL 14 DAY)
    UNION ALL SELECT 15, DATE_SUB(CURDATE(), INTERVAL 15 DAY)
    UNION ALL SELECT 16, DATE_SUB(CURDATE(), INTERVAL 16 DAY)
    UNION ALL SELECT 17, DATE_SUB(CURDATE(), INTERVAL 17 DAY)
    UNION ALL SELECT 18, DATE_SUB(CURDATE(), INTERVAL 18 DAY)
    UNION ALL SELECT 19, DATE_SUB(CURDATE(), INTERVAL 19 DAY)
    UNION ALL SELECT 20, DATE_SUB(CURDATE(), INTERVAL 20 DAY)
    UNION ALL SELECT 21, DATE_SUB(CURDATE(), INTERVAL 21 DAY)
    UNION ALL SELECT 22, DATE_SUB(CURDATE(), INTERVAL 22 DAY)
    UNION ALL SELECT 23, DATE_SUB(CURDATE(), INTERVAL 23 DAY)
    UNION ALL SELECT 24, DATE_SUB(CURDATE(), INTERVAL 24 DAY)
    UNION ALL SELECT 25, DATE_SUB(CURDATE(), INTERVAL 25 DAY)
    UNION ALL SELECT 26, DATE_SUB(CURDATE(), INTERVAL 26 DAY)
    UNION ALL SELECT 27, DATE_SUB(CURDATE(), INTERVAL 27 DAY)
    UNION ALL SELECT 28, DATE_SUB(CURDATE(), INTERVAL 28 DAY)
    UNION ALL SELECT 29, DATE_SUB(CURDATE(), INTERVAL 29 DAY)
) AS dt
CROSS JOIN (
    SELECT 2 AS indicator_id, 1 AS has_metric_value
    UNION ALL SELECT 3, 1
    UNION ALL SELECT 4, 1
    UNION ALL SELECT 5, 1
    UNION ALL SELECT 6, 1
    UNION ALL SELECT 7, 1
    UNION ALL SELECT 9, 0
    UNION ALL SELECT 10, 0
    UNION ALL SELECT 11, 0
    UNION ALL SELECT 12, 0
    UNION ALL SELECT 13, 0
    UNION ALL SELECT 14, 0
    UNION ALL SELECT 15, 0
    UNION ALL SELECT 16, 0
    UNION ALL SELECT 17, 0
    UNION ALL SELECT 18, 0
    UNION ALL SELECT 19, 0
    UNION ALL SELECT 21, 0
    UNION ALL SELECT 22, 0
    UNION ALL SELECT 23, 0
    UNION ALL SELECT 24, 0
    UNION ALL SELECT 25, 0
    UNION ALL SELECT 26, 0
) AS ind
CROSS JOIN (
    SELECT '44030101' AS org_id, 1 AS org_idx
    UNION ALL SELECT '44030102', 2
    UNION ALL SELECT '44030105', 3
    UNION ALL SELECT '44030106', 4
    UNION ALL SELECT '44030109', 5
    UNION ALL SELECT '44030110', 6
    UNION ALL SELECT '44039001', 7
    UNION ALL SELECT '44039002', 8
    UNION ALL SELECT '44039003', 9
    UNION ALL SELECT '44039004', 10
    UNION ALL SELECT '44030003', 11
    UNION ALL SELECT '44030004', 12
) AS org;
